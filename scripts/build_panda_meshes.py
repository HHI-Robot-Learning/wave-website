"""Convert the Franka Panda link meshes of rai-robotModels into static/js/panda_meshes.js.

    ../26-MOGB/.venv/bin/python scripts/build_panda_meshes.py [path/to/rai-robotModels/panda]

Each rai mesh (meshes/<name>.h5: vertices, faces, per-vertex colors) is stored in its link's
own frame, as rai draws it. Vertices are quantized to 0.1 mm (int16), faces kept as uint16, and
everything is base64-encoded, so the 3-D view needs no mesh loader.
"""
import base64
import json
import sys
from pathlib import Path

import h5py
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "rai-robotModels/panda"
OUT = ROOT / "static/js/panda_meshes.js"
NAMES = ["link0", "link1", "link2", "link3", "link4", "link5", "link6", "link7", "hand", "finger"]
SCALE = 1e-4  # metres per quantization step


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()


meshes = {}
for name in NAMES:
    with h5py.File(SRC / "meshes" / f"{name}.h5", "r") as f:
        v, fc = f["mesh/vertices"][()], f["mesh/faces"][()]
        col = f["mesh/colors"][()] if "mesh/colors" in f else np.full((len(v), 3), 230, np.uint8)
    q = np.round(v / SCALE)
    assert np.abs(q).max() < 32767, name
    assert fc.max() < 65536, name
    meshes[name] = {"v": b64(q.astype("<i2")), "f": b64(fc.astype("<u2")), "c": b64(col.astype(np.uint8))}
    print(f"{name:7s} {len(v):6d} vertices {len(fc):6d} faces")

OUT.write_text("// Generated by scripts/build_panda_meshes.py from rai-robotModels/panda. Do not edit.\n"
               f"window.PANDA_MESHES = {{\"scale\": {SCALE}, \"meshes\": " + json.dumps(meshes) + "};\n")
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB)")
