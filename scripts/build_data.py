"""Build static/js/data.js for the interactive charts from the paper's count_curve_data.csv.

    python scripts/build_data.py [path/to/count_curve_data.csv]

Defaults to ../2026-ICLR-WAVE-NEW/figures/count_curve_data.csv next to this repository.
"""
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "2026-ICLR-WAVE-NEW/figures/count_curve_data.csv"
OUT = ROOT / "static/js/data.js"

# Same labels and colors as the paper's count_curve.py.
GRAY = "#9aa0a6"
TASKS = {
    "tower3": ("stacking (h=3)", "#1f5fbf"),
    "tower6": ("stacking (h=6)", "#5fa8e8"),
    "square": ("square 3×3", "#7b3fa0"),
    "wall": ("wall", "#b8701e"),
    "line": ("line", "#2a8f5c"),
    "pyramid": ("pyramid", "#c2443c"),
}
PUBLISHED = {
    "pub_li2020": "Li et al. '20, stacking",
    "pub_ecrl": "ECRL '24, pushing (pixels)",
    "pub_hecrl": "HECRL '26, rearrangement",
    "pub_pair": "PAIR '22 (one target cube)",
    "pub_lanier": "Lanier et al. '19",
    "pub_ogbench": "OGBench '24, stacking",
    "pub_sharsa_mean": "SHARSA '25, five-goal mean",
    "pub_sharsa_stack": "SHARSA '25, stacking",
}
# Direct labels for the published series: (x, y, anchor), copied from PUB_LABEL_POS in the paper's
# count_curve.py; anchor is the point a leader line runs to, or None.
PUB_LABEL_POS = {
    "pub_li2020": (6.5, 0.67, None),
    "pub_ecrl": (6.5, 0.47, None),
    "pub_hecrl": (6.5, 0.25, None),
    "pub_pair": (6.5, 0.865, None),
    "pub_lanier": (7.3, 0.57, (4, 0.79)),
    "pub_ogbench": (2.8, 0.10, None),
    "pub_sharsa_mean": (8.4, 0.36, None),
    "pub_sharsa_stack": (8.3, 0.05, None),
}
BASELINES = {
    "wave": ("WAVE", "#1f5fbf"),
    "skill_alone": ("skill alone (μ)", "#9a2e35"),
    "finetune": ("fine-tune μ", "#2a8f5c"),
    "cropft1": ("fine-tune μ + crop, ω=1", "#d4a017"),
    "cropft0": ("fine-tune μ + crop, ω=0", "#8c6d3f"),
    "jsrl": ("JSRL", "#7b3fa0"),
    "hrl": ("HRL subgoals", "#c2443c"),
    "croptd7": ("TD7 on the crop", "#3f8fa0"),
    "eit": ("EIT, all entities", "#b8701e"),
    "eit_distilled": ("EIT distilled from μ", "#3a3a3a"),
}
ABLATIONS = {
    "selection": {"sel_analytic": ("nearest first", "#2a8f5c"), "sel_random": ("random", "#c2443c")},
    "side": {"input_only": ("input side only", "#2a8f5c"), "output_only": ("output side only", "#7b3fa0")},
    "component": {"slope_only": ("multipliers only", "#3a3a3a"), "offset_only": ("offsets only", "#b8701e")},
}
ABL_TASKS = ["tower3", "square", "pyramid"]

rows = defaultdict(list)
with open(SRC) as f:
    for r in csv.reader(line for line in f if not line.startswith("#")):
        if r[0] == "series":
            continue
        lo = float(r[5]) if r[5] else None
        hi = float(r[6]) if r[6] else None
        rows[r[0]].append([int(r[3]), float(r[4]), lo, hi])
for pts in rows.values():
    pts.sort()


def series(key, label, color, **extra):
    return dict(key=key, label=label, color=color, pts=rows[key], **extra)


data = {
    "gantry": [series(f"ours_{t}", l, c) for t, (l, c) in TASKS.items()]
    + [series("skill_alone", "skill alone, stacking (h=3)", "#9a2e35", dash=True)]
    + [series(k, l, GRAY, published=True, label_pos=PUB_LABEL_POS[k]) for k, l in PUBLISHED.items()],
    "panda": [series(f"panda_{t}", l, c) for t, (l, c) in TASKS.items() if rows.get(f"panda_{t}")],
    "baselines": {
        task: [series(f"bl_{arm}_{task}", l, c, dash=arm == "skill_alone") for arm, (l, c) in BASELINES.items()
               if rows.get(f"bl_{arm}_{task}")]
        for task in ["line", "tower3"]
    },
    "ablations": {
        kind: {
            task: [series(f"ours_{task}", "WAVE (full)", "#1f5fbf")]
            + [series(f"abl_{arm}_{task}", l, c) for arm, (l, c) in arms.items()]
            for task in ABL_TASKS
        }
        for kind, arms in ABLATIONS.items()
    },
}

OUT.write_text("// Generated by scripts/build_data.py from count_curve_data.csv. Do not edit by hand.\n"
               "window.WAVE_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
